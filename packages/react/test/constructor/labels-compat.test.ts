function pick<K extends string>(
  source: Record<string, unknown>,
  keys: readonly K[],
): Record<K, Label> {
  const out = {} as Record<K, Label>;
  for (const key of keys) out[key] = source[key] as Label;
  return out;
}

const oldEditor: Record<FirstReleaseEditorKey, Label> = pick(
  editorLabelsEn as unknown as Record<string, unknown>,
  FIRST_RELEASE_EDITOR_KEYS,
);
const typedEditor: EditorLabels = oldEditor;

const oldPicker: Record<FirstReleasePickerKey, Label> & {
  status: { available: Label; taken: Label; held: Label; blocked: Label; selected: Label };
  zones: Record<string, Label>;
  violations: Record<string, Label>;
  priceSign: string;
} = {
  priceSign: '¤',
  ...pick(labels.en.picker as unknown as Record<string, unknown>, FIRST_RELEASE_PICKER_KEYS),
  status: {
    available: 'Free',
    taken: 'Sold',
    held: 'On hold',
    blocked: 'Unavailable',
    selected: 'Selected',
  },
  zones: {},
  violations: {},
};
const typedPicker: PickerLabels = oldPicker;
const typedLabels: Labels = { picker: oldPicker, editor: oldEditor };

describe('label catalogs written for an older version', () => {
  it('compile and fall back to English for the keys added later', () => {
    expect(Object.keys(typedEditor)).toHaveLength(FIRST_RELEASE_EDITOR_KEYS.length);
    expect(typedEditor).not.toHaveProperty('allSaved');
    expect(editorLabel(typedEditor, 'allSaved')).toBe('All changes saved');
    expect(editorLabel(typedEditor, 'issuePlace')).toBe('{band} › {section}');
    expect(editorLabel(typedLabels.editor, 'cBalconySlabThickness')).toBe(
      'Balcony floor thickness',
    );
    expect(pickerLabel(typedPicker, 'confirmPurchase')).toBe('Confirm purchase · {price}');
  });

  it('every key of the built-in English catalog is set', () => {
    for (const value of Object.values(editorLabelsEn)) expect(value).toBeTruthy();
  });
});
